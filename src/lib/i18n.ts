const STORAGE_KEY = 'cvision-lang';

export function getStoredLang(): LangCode {
  if (typeof localStorage !== 'undefined') {
    const stored = localStorage.getItem(STORAGE_KEY) as LangCode | null;
    if (stored && translations[stored]) return stored;
  }
  return 'en';
}

export function storeLang(lang: LangCode) {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, lang);
  }
}

export function t(lang: LangCode, key: TranslationKey): string {
  return translations[lang]?.[key] || translations.en[key] || key;
}

export function isRTL(lang: LangCode): boolean {
  return lang === 'ar';
}
